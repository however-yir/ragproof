#!/usr/bin/env python3
"""Generate the MkDocs benchmark fragments from one ragproof run artifact."""

from __future__ import annotations

import argparse
import json
import re
import tempfile
from pathlib import Path
from typing import Any

from ragproof.report import render


def _metric(run: dict[str, Any], name: str) -> float:
    return float(run["aggregate"][name])


def render_summary(run: dict[str, Any]) -> str:
    """Render the compact homepage summary from the current benchmark run."""
    sample_count = int(run["sample_count"])
    context_coverage = run["coverage"]["fields"]["contexts"]
    available = int(context_coverage["available"])
    rate = float(context_coverage["rate"])
    git_sha = str(run.get("git_sha") or "unknown")

    return f"""<!-- Generated by scripts/generate_public_benchmark_docs.py. -->
<div class=\"benchmark-grid\">
  <div class=\"benchmark-card\"><strong>{sample_count}</strong><span>English and Chinese synthetic questions</span></div>
  <div class=\"benchmark-card\"><strong>{_metric(run, 'recall@3'):.3f} / {_metric(run, 'mrr'):.3f}</strong><span>recall@3 / MRR</span></div>
  <div class=\"benchmark-card\"><strong>{_metric(run, 'citation_validity'):.3f}</strong><span>citation validity</span></div>
  <div class=\"benchmark-card\"><strong>{_metric(run, 'error_rate'):.3f}</strong><span>error rate</span></div>
</div>

The current run has {available}/{sample_count} samples with context ({rate:.1%}); deliberately unanswerable samples return no context or citation by design. The complete report records commit `{git_sha}`, fingerprints, all metric coverage, group slices, and per-sample evidence.
"""


def demote_headings(markdown: str) -> str:
    """Nest a standalone report safely below the wrapper page heading."""
    return re.sub(r"^(#{1,5})(?= )", r"#\1", markdown, flags=re.MULTILINE)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("run", type=Path)
    parser.add_argument(
        "--summary",
        type=Path,
        default=Path("docs/includes/public-benchmark-summary.inc"),
    )
    parser.add_argument(
        "--details",
        type=Path,
        default=Path("docs/includes/public-benchmark-details.inc"),
    )
    args = parser.parse_args()

    run = json.loads(args.run.read_text(encoding="utf-8"))
    args.summary.parent.mkdir(parents=True, exist_ok=True)
    args.details.parent.mkdir(parents=True, exist_ok=True)
    args.summary.write_text(render_summary(run), encoding="utf-8")

    with tempfile.TemporaryDirectory() as temp_dir:
        standalone = Path(temp_dir) / "report.md"
        render(args.run, standalone)
        details = demote_headings(standalone.read_text(encoding="utf-8"))
    args.details.write_text(details, encoding="utf-8")


if __name__ == "__main__":
    main()
